"""Write the projector-preview test stages (no UVs anywhere: a projector needs none).

    python3 tools/scenes/make_projector_fixtures.py tests/fixtures/scenes/projector

Metres, Y up, the audience at +Z. Every face is wound counter-clockwise seen from its front, so
its normal is known:
projection.obj
  Wall      12 x 5 m at z = 0, x -6..6, y 0..5, facing +Z
  Occluder  1 x 1 m at z = 2, centred (1, 1.5), facing +Z
  Backface  0.6 x 0.6 m at z = 1, centred (-1.2, 2.5), facing -Z (away from a projector in front)
  Plaque    0.5 x 0.5 m at z = 0.05 (5 cm proud of the wall), centred (-0.5, 1.2), facing +Z
  Rear      6 x 4 m at z = 14, x -3..3, y 0..4, facing -Z (towards the wall)
curve.obj
  Curve     a half cylinder, radius 1.5 m, axis vertical through x = 0, z = 0, y 0..3,
            from -80° to +80° around +Z, 64 segments, facing outwards
"""
import math
import os
import sys

OUT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else "tests/fixtures/scenes/projector")


def quad(name, corners):
    """corners counter-clockwise seen from the front."""
    return name, list(corners), [(0, 1, 2, 3)]


def plane_z(name, x0, x1, y0, y1, z, front=+1):
    c = [(x0, y0, z), (x1, y0, z), (x1, y1, z), (x0, y1, z)]
    return quad(name, c if front > 0 else c[::-1])


def square(name, cx, cy, z, size, front=+1):
    h = size / 2
    return plane_z(name, cx - h, cx + h, cy - h, cy + h, z, front)


def curve(name, r=1.5, y0=0.0, y1=3.0, a0=-80, a1=80, n=64):
    verts, faces = [], []
    for i in range(n + 1):
        a = math.radians(a0 + (a1 - a0) * i / n)
        x, z = r * math.sin(a), r * math.cos(a)
        verts += [(x, y0, z), (x, y1, z)]
    for i in range(n):
        b, t, b2, t2 = 2 * i, 2 * i + 1, 2 * i + 2, 2 * i + 3
        faces.append((b, b2, t2, t))                  # outward (+Z side) is the front
    return name, verts, faces


def write(path, objects):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    lines, base = ["# generated by tools/scenes/make_projector_fixtures.py; no UVs"], 1
    for name, verts, faces in objects:
        lines.append(f"o {name}")
        lines += [f"v {x:.6g} {y:.6g} {z:.6g}" for x, y, z in verts]
        lines += ["f " + " ".join(str(base + i) for i in f) for f in faces]
        base += len(verts)
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")


write(os.path.join(OUT, "projection.obj"), [
    plane_z("Wall", -6, 6, 0, 5, 0.0),
    square("Occluder", 1.0, 1.5, 2.0, 1.0),
    square("Backface", -1.2, 2.5, 1.0, 0.6, front=-1),
    square("Plaque", -0.5, 1.2, 0.05, 0.5),
    plane_z("Rear", -3, 3, 0, 4, 14.0, front=-1),
])
write(os.path.join(OUT, "curve.obj"), [curve("Curve")])
print("wrote", OUT)
